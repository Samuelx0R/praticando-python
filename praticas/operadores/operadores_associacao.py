# Utilizados para verificar se algo pertence a outro algo

frutas = ["laranja", "uva", "limão"]
curso = "Curso de python"

# in - verifica se algo está contido a outro algo 
print("Python" in curso)

# not in - verifica se algo não está contido a outro algo
print("maça" not in frutas)

# é CASE SENSITIVE, precisa ser o mesmo valor Laranja e laranja são coisas diferentes