# adição
print(1 + 1)

# subtração
print(3 - 1)

# multiplicação
print(2 * 1)

# divisão
print(4 / 2)

# divisão inteira
print(4 // 2)

# módulo (resto de divisão)
print(11 % 3)

# exponenciação (potência)
print(2 ** 1)

