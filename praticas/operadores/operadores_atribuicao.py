# tipos de atribuição:

# 1. atribuição simples: = (a varíavel recebe o valor)
# 2. atribuição com adição: += soma o valor já contido na variável com outro valor
# 2.1. atribuições parecidas: -=, *=, /=, //=, %=, **= que aplicam o operador aritmético

valor = 20
print(valor)

valor += 10
print(valor)

valor -= 10
print(valor)

valor *= 10
print(valor)

valor //= 10
print(valor)

valor /= 10
print(valor)

valor %= 10
print(valor)

valor **= 10
print(valor)